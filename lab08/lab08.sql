SELECT table_name,constraint_name,constraint_type FROM information_schema.table_constraints
WHERE table_schema='lab' AND table_name IN('coupons','coupon_categories','coupon_uses')
ORDER BY table_name,constraint_name;
SELECT 'coupons' AS relation,count(*) FROM lab.coupons UNION ALL
SELECT 'coupon_categories',count(*) FROM lab.coupon_categories UNION ALL
SELECT 'coupon_uses',count(*) FROM lab.coupon_uses;
-- Межстрочные правила (лимит, срок, категория заказа) проверяются диагностикой.
SELECT u.use_id FROM lab.coupon_uses u JOIN lab.coupons c USING(coupon_id)
WHERE u.used_at<c.valid_from OR u.used_at>=c.valid_to OR NOT EXISTS
 (SELECT 1 FROM olist.order_items i JOIN olist.products p USING(product_id)
  WHERE i.order_id=u.order_id AND p.product_category_name=u.category_name);
SELECT c.coupon_code FROM lab.coupons c LEFT JOIN lab.coupon_uses u USING(coupon_id)
GROUP BY c.coupon_id HAVING count(u.use_id)>c.usage_limit;
