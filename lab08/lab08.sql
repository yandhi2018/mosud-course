SET max_parallel_workers_per_gather = 0;
CREATE SCHEMA IF NOT EXISTS lab;
CREATE TABLE IF NOT EXISTS lab.coupons (
 coupon_id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_coupons PRIMARY KEY,
 coupon_code text NOT NULL CONSTRAINT uq_coupons_code UNIQUE,
 issuer_seller_id text NOT NULL CONSTRAINT fk_coupons_seller REFERENCES olist.sellers(seller_id),
 valid_from timestamp NOT NULL, valid_to timestamp NOT NULL,
 discount_pct numeric(5,2) NOT NULL, usage_limit integer NOT NULL,
 CONSTRAINT ck_coupons_dates CHECK(valid_from<valid_to),
 CONSTRAINT ck_coupons_discount CHECK(discount_pct>0 AND discount_pct<=100),
 CONSTRAINT ck_coupons_limit CHECK(usage_limit>0));
CREATE TABLE IF NOT EXISTS lab.coupon_categories (
 coupon_id bigint NOT NULL CONSTRAINT fk_categories_coupon REFERENCES lab.coupons(coupon_id),
 category_name text NOT NULL CONSTRAINT fk_categories_olist
 REFERENCES olist.product_category_name_translation(product_category_name),
 CONSTRAINT pk_coupon_categories PRIMARY KEY(coupon_id,category_name));
CREATE TABLE IF NOT EXISTS lab.coupon_uses (
 use_id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_coupon_uses PRIMARY KEY,
 coupon_id bigint NOT NULL CONSTRAINT fk_uses_coupon REFERENCES lab.coupons(coupon_id),
 order_id text NOT NULL CONSTRAINT fk_uses_order REFERENCES olist.orders(order_id),
 category_name text NOT NULL,used_at timestamp NOT NULL,
 discount_amount numeric(10,2) NOT NULL,
 CONSTRAINT uq_coupon_uses_order UNIQUE(coupon_id,order_id),
 CONSTRAINT fk_uses_category FOREIGN KEY(coupon_id,category_name)
 REFERENCES lab.coupon_categories(coupon_id,category_name),
 CONSTRAINT ck_uses_amount CHECK(discount_amount>0));
-- Используем реальные позиции доставленных заказов, их продавцов и категории.
CREATE TEMP TABLE coupon_seed AS
SELECT row_number() OVER(ORDER BY order_id) AS n,q.* FROM (
 SELECT DISTINCT ON(o.order_id) o.order_id,i.seller_id,p.product_category_name,
 o.order_purchase_timestamp AS purchased_at,i.price
 FROM olist.orders o JOIN olist.order_items i USING(order_id)
 JOIN olist.products p USING(product_id)
 JOIN olist.product_category_name_translation t USING(product_category_name)
 WHERE o.order_status='delivered' AND i.price>0
 ORDER BY o.order_id,i.order_item_id LIMIT 5) q;
INSERT INTO lab.coupons(coupon_code,issuer_seller_id,valid_from,valid_to,discount_pct,usage_limit)
SELECT 'MOSUD04_'||n,seller_id,purchased_at-interval '1 day',purchased_at+interval '30 days',10,5
FROM coupon_seed ON CONFLICT(coupon_code) DO NOTHING;
INSERT INTO lab.coupon_categories
SELECT c.coupon_id,s.product_category_name FROM coupon_seed s
JOIN lab.coupons c ON c.coupon_code='MOSUD04_'||s.n ON CONFLICT DO NOTHING;
INSERT INTO lab.coupon_uses(coupon_id,order_id,category_name,used_at,discount_amount)
SELECT c.coupon_id,s.order_id,s.product_category_name,s.purchased_at,round(s.price*0.1,2)
FROM coupon_seed s JOIN lab.coupons c ON c.coupon_code='MOSUD04_'||s.n
ON CONFLICT(coupon_id,order_id) DO NOTHING;
